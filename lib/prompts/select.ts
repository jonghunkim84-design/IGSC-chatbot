export function buildHistoryListBlock(rows: { cert_type: string; product_category: string | null }[]): string {
  return `인증 이력 목록:\n${rows.map((r, i) => `${i + 1}. [${certName(r.cert_type)}] ${r.product_category ?? "(제품군 미상)"}`).join("\n")}`;
}
