export interface FaqListItem {
  question: string;
  variants: string[];
  cert_type: string;
}

/** 번호는 1부터. 이 블록은 프롬프트 캐싱 대상이므로 고객 질문을 넣지 않는다. */
export function buildFaqListBlock(items: FaqListItem[]): string {
  const lines = items.map((it, i) => {
    const v = it.variants.length ? ` (다른 표현: ${it.variants.join(" / ")})` : "";
    return `${i + 1}. [${it.cert_type === "common" ? "공통" : it.cert_type}] ${it.question}${v}`;
  });
  return `FAQ 목록:\n${lines.join("\n")}`;
}

export function buildSelectUserMessage(query: string, opts: { commonOnly?: boolean } = {}): string {
  // 공통 항목 목록만 보여줄 때: 고객이 인증 이름을 말했더라도 목록에 그 인증이 없다는 이유로 제외하지 않게 한다.
  const note = opts.commonOnly
    ? "\n(이 목록은 모든 인증에 공통으로 적용되는 항목만 모은 것입니다. 고객이 특정 인증 이름을 말했더라도 인증 종류는 따지지 말고, 고객이 묻는 정보의 종류(절차, 서류 등)에 답이 되는 항목만 고르세요.)"
    : "";
  return `고객 질문:\n<question>\n${query}\n</question>${note}\n\n관련 FAQ 번호를 JSON 배열로만 출력하세요.`;
}

